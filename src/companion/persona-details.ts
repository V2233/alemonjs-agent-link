export type PersonaDetails = Partial<Record<(typeof personaDetailFields)[number], string>>;
export const validatePersonaDetails = (value: unknown): PersonaDetails => {
  if (value === undefined) return {};
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error('人设细节格式无效');
  const result: PersonaDetails = {};

  for (const [key, text] of Object.entries(value)) {
    if (!personaDetailFields.includes(key as (typeof personaDetailFields)[number]) || typeof text !== 'string' || text.length > 1200)
      throw new Error('人设细节字段无效或超过1200字');
    result[key] = text.trim();
  }
  if (Object.values(result).join('').length > 10000) throw new Error('人设细节累计最多10000字');

  return result;
};
